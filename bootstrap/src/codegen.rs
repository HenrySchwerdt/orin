//! Codegen: typed HIR → GNU C source using runtime/orin_runtime.h. Owned by the codegen worker.
//!
//! Conventions (docs/architecture.md): parameters borrowed, returns owned, locals own their
//! value, storing a borrowed value retains it, owned temporaries that are only borrowed are
//! released after use, locals are released at scope exit / break / continue / return.
//! Early exits from inside expressions (`?`, diverging match arms) may leak temporaries.
//!
//! Every Orin local `n` becomes C local `l<n>`; all non-parameter locals are declared (and
//! NULL/0-initialised) at function entry. Expressions compile to C expressions (GNU statement
//! expressions where temporaries are needed); each carries an ownership flag (`Val`).

use crate::hir::*;
use std::collections::HashMap;
use std::fmt::Write;

#[cfg(test)]
mod tests;

/// Maximum number of fields of a record / payload slots of a variant (ref bitmask is 64 bits).
const MAX_SLOTS: usize = 64;

pub fn generate(prog: &Program) -> String {
    let mut g = Gen { prog, strings: Vec::new(), string_ids: HashMap::new() };
    let names: Vec<String> =
        prog.functions.iter().enumerate().map(|(i, f)| format!("orin_fn_{}_{}", i, sanitize(&f.name))).collect();
    let mut bodies = String::new();
    let mut decls = String::new();
    for (i, f) in prog.functions.iter().enumerate() {
        let sig = signature(&names[i], f);
        let _ = writeln!(decls, "{};", sig);
        let mut fg = FnGen { g: &mut g, names: &names, func: f, tmp: 0, scopes: Vec::new(), loops: Vec::new() };
        let body = fg.function(&sig);
        bodies.push_str(&body);
        bodies.push('\n');
    }
    let mut out = String::new();
    out.push_str("/* Generated by orinb (Orin Stage 0). Do not edit. */\n#include \"orin_runtime.h\"\n\n");
    for (i, s) in g.strings.iter().enumerate() {
        let _ = writeln!(out, "ORIN_STRING_LIT(orin_s{}, {}, {});", i, s.len(), c_string(s.as_bytes()));
    }
    out.push('\n');
    out.push_str(&decls);
    out.push('\n');
    out.push_str(&bodies);
    let _ = write!(
        out,
        "int main(int argc, char **argv) {{\n  orin_init(argc, argv);\n  {}();\n  orin_flush();\n  return 0;\n}}\n",
        names[prog.main.0 as usize]
    );
    out
}

fn sanitize(name: &str) -> String {
    name.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }).collect()
}

/// C string literal with octal escapes for everything but safe printable ASCII.
fn c_string(bytes: &[u8]) -> String {
    let mut s = String::from("\"");
    for &b in bytes {
        match b {
            b'"' => s.push_str("\\\""),
            b'\\' => s.push_str("\\\\"),
            b'?' => s.push_str("\\?"),
            0x20..=0x7e => s.push(b as char),
            _ => {
                let _ = write!(s, "\\{:03o}", b);
            }
        }
    }
    s.push('"');
    s
}

fn cty(t: &Type) -> &'static str {
    match t {
        Type::Int | Type::Bool => "int64_t",
        Type::Usize => "uint64_t",
        Type::Void => "void",
        _ => "OrinObj *",
    }
}

fn is_ref(t: &Type) -> bool {
    !t.is_scalar()
}

/// Convert a C slot value (uint64_t) into the C representation of `t`.
fn from_slot(t: &Type, code: &str) -> String {
    match t {
        Type::Void => format!("((void)({}))", code),
        _ if is_ref(t) => format!("ORIN_REF({})", code),
        _ => format!("(({})({}))", cty(t), code),
    }
}

fn to_slot(t: &Type, code: &str) -> String {
    if is_ref(t) {
        format!("ORIN_SLOT({})", code)
    } else {
        format!("((uint64_t)({}))", code)
    }
}

fn signature(name: &str, f: &Function) -> String {
    let mut s = format!("{} {}(", cty(&f.ret), name);
    if f.param_count == 0 {
        s.push_str("void");
    }
    for i in 0..f.param_count as usize {
        if i > 0 {
            s.push_str(", ");
        }
        let _ = write!(s, "{} l{}", cty(&f.locals[i].ty), i);
    }
    s.push(')');
    s
}

fn mask_of<'a>(tys: impl Iterator<Item = &'a Type>) -> u64 {
    let mut m = 0u64;
    for (i, t) in tys.enumerate() {
        assert!(i < MAX_SLOTS, "codegen: more than 64 slots in one record/variant");
        if is_ref(t) {
            m |= 1 << i;
        }
    }
    m
}

struct Gen<'a> {
    #[allow(dead_code)]
    prog: &'a Program,
    strings: Vec<String>,
    string_ids: HashMap<String, usize>,
}

impl Gen<'_> {
    fn intern(&mut self, s: &str) -> usize {
        if let Some(&i) = self.string_ids.get(s) {
            return i;
        }
        let i = self.strings.len();
        self.strings.push(s.to_string());
        self.string_ids.insert(s.to_string(), i);
        i
    }
}

/// Result of compiling an expression: C code plus ownership of the (non-scalar) value.
struct Val {
    code: String,
    /// The value is a fresh +1 reference the consumer must release or store.
    owned: bool,
    /// Immortal (static literal / singleton): needs no retain or release.
    imm: bool,
}

impl Val {
    fn owned(code: String) -> Val {
        Val { code, owned: true, imm: false }
    }
    fn borrowed(code: String) -> Val {
        Val { code, owned: false, imm: false }
    }
    fn imm(code: String) -> Val {
        Val { code, owned: false, imm: true }
    }
}

#[derive(Clone, Copy, PartialEq)]
enum Kind {
    /// Fresh owned (or scalar) result.
    Fresh,
    /// Borrowed from one of the arguments.
    Borrowed,
    Void,
}

/// An expression with no side effects that is cheap to evaluate (safe to inline in any order).
fn is_simple(e: &Expr) -> bool {
    match &e.kind {
        ExprKind::Int(_) | ExprKind::Bool(_) | ExprKind::Str(_) | ExprKind::Local(_) => true,
        ExprKind::Field { base, .. } => is_simple(base),
        _ => false,
    }
}

/// May evaluating `e` change the value of a local (assignment/mutation inside the expression)?
fn has_effects(e: &Expr) -> bool {
    match &e.kind {
        ExprKind::Int(_) | ExprKind::Bool(_) | ExprKind::Str(_) | ExprKind::Local(_) => false,
        ExprKind::Unary { expr, .. } => has_effects(expr),
        ExprKind::Binary { lhs, rhs, .. } => has_effects(lhs) || has_effects(rhs),
        ExprKind::Call { args, .. } | ExprKind::Builtin { args, .. } => args.iter().any(has_effects),
        ExprKind::MutMethod { .. } => true,
        ExprKind::Field { base, .. } => has_effects(base),
        ExprKind::Index { base, index } => has_effects(base) || has_effects(index),
        ExprKind::Record { spread, fields, .. } => {
            spread.as_deref().is_some_and(has_effects) || fields.iter().any(|(_, f)| has_effects(f))
        }
        ExprKind::Variant { payload, .. } => payload.iter().any(has_effects),
        ExprKind::Array(xs) => xs.iter().any(has_effects),
        ExprKind::Try(x) => has_effects(x),
        ExprKind::Cond { cond, then, els } => has_effects(cond) || has_effects(then) || has_effects(els),
        ExprKind::Match { scrutinee, arms } => {
            has_effects(scrutinee)
                || arms.iter().any(|a| !a.body.stmts.is_empty() || a.value.as_ref().is_some_and(has_effects))
        }
    }
}

struct FnGen<'a, 'g> {
    g: &'a mut Gen<'g>,
    names: &'a [String],
    func: &'a Function,
    tmp: u32,
    /// Stack of scopes; each lists the C variables (owned references) to release when it exits.
    scopes: Vec<Vec<String>>,
    /// For each enclosing loop, the index in `scopes` of its "outer" scope (released by `break`).
    loops: Vec<usize>,
}

impl FnGen<'_, '_> {
    fn fresh(&mut self) -> u32 {
        self.tmp += 1;
        self.tmp
    }

    fn local_ty(&self, id: LocalId) -> &Type {
        &self.func.locals[id.0 as usize].ty
    }

    // ------------------------------------------------------------ functions

    fn function(&mut self, sig: &str) -> String {
        let f = self.func;
        let mut out = format!("{} {{\n", sig);
        for (i, l) in f.locals.iter().enumerate().skip(f.param_count as usize) {
            let init = if is_ref(&l.ty) { "NULL" } else { "0" };
            let _ = writeln!(out, "  {} l{} = {}; /* {} */", cty(&l.ty), i, init, l.name.replace("*/", "* /"));
        }
        self.scopes.push(Vec::new());
        for s in &f.body.stmts {
            self.stmt(s, &mut out);
        }
        out.push_str(&self.release_from(0));
        self.scopes.pop();
        if f.ret != Type::Void {
            out.push_str("  orin_trap(\"missing return\");\n");
        }
        out.push_str("}\n");
        out
    }

    /// Release statements for every variable in scopes[from..], innermost first.
    fn release_from(&self, from: usize) -> String {
        let mut s = String::new();
        for sc in self.scopes[from..].iter().rev() {
            for v in sc.iter().rev() {
                let _ = write!(s, "orin_release({}); ", v);
            }
        }
        s
    }

    // ------------------------------------------------------------ statements

    fn block(&mut self, b: &Block, out: &mut String) {
        out.push_str("{\n");
        self.scopes.push(Vec::new());
        for s in &b.stmts {
            self.stmt(s, out);
        }
        out.push_str(&self.release_from(self.scopes.len() - 1));
        self.scopes.pop();
        out.push_str("\n}\n");
    }

    fn stmt(&mut self, s: &Stmt, out: &mut String) {
        match s {
            Stmt::Let { local, init } => {
                let ty = self.local_ty(*local).clone();
                let v = self.consume(init);
                let _ = writeln!(out, "l{} = {};", local.0, v);
                if is_ref(&ty) {
                    self.scopes.last_mut().unwrap().push(format!("l{}", local.0));
                }
            }
            Stmt::Assign { place, op, value } => self.assign(place, *op, value, out),
            Stmt::Expr(e) => {
                let v = self.expr(e);
                if e.ty == Type::Void {
                    let _ = writeln!(out, "{};", v.code);
                } else if v.owned && is_ref(&e.ty) {
                    let _ = writeln!(out, "orin_release({});", v.code);
                } else {
                    let _ = writeln!(out, "(void)({});", v.code);
                }
            }
            Stmt::If { cond, then, els } => {
                let c = self.expr(cond);
                let _ = writeln!(out, "if ({}) ", c.code);
                self.block(then, out);
                if let Some(e) = els {
                    out.push_str("else ");
                    self.block(e, out);
                }
            }
            Stmt::While { cond, body } => {
                self.scopes.push(Vec::new());
                self.loops.push(self.scopes.len() - 1);
                let c = self.expr(cond);
                let _ = writeln!(out, "while ({}) ", c.code);
                self.block(body, out);
                self.loops.pop();
                self.scopes.pop();
            }
            Stmt::ForOf { local, iter, body } => {
                let id = self.fresh();
                let (it, ix) = (format!("_it{}", id), format!("_i{}", id));
                let lty = self.local_ty(*local).clone();
                let src = self.consume(iter);
                let _ = writeln!(out, "{{\nOrinObj *{} = {};", it, src);
                self.scopes.push(vec![it.clone()]);
                self.loops.push(self.scopes.len() - 1);
                let _ = writeln!(out, "for (uint64_t {ix} = 0; {ix} < orin_array_len({it}); {ix}++) {{");
                let elem = from_slot(&lty, &format!("orin_array_at({it}, {ix})"));
                let mut sc = Vec::new();
                if is_ref(&lty) {
                    let _ = writeln!(out, "l{} = orin_dup({});", local.0, elem);
                    sc.push(format!("l{}", local.0));
                } else {
                    let _ = writeln!(out, "l{} = {};", local.0, elem);
                }
                self.scopes.push(sc);
                for st in &body.stmts {
                    self.stmt(st, out);
                }
                out.push_str(&self.release_from(self.scopes.len() - 1));
                self.scopes.pop();
                out.push_str("\n}\n");
                self.loops.pop();
                self.scopes.pop();
                let _ = writeln!(out, "orin_release({});\n}}", it);
            }
            Stmt::Break => {
                // the loop-outer scope (e.g. the iterated array) is released after the loop
                let l = *self.loops.last().expect("break outside loop");
                out.push_str(&self.release_from(l + 1));
                out.push_str("break;\n");
            }
            Stmt::Continue => {
                let l = *self.loops.last().expect("continue outside loop");
                out.push_str(&self.release_from(l + 1));
                out.push_str("continue;\n");
            }
            Stmt::Return(e) => {
                match e {
                    Some(e) if self.func.ret != Type::Void => {
                        let v = self.consume(e);
                        let _ = writeln!(out, "{{ {} _rv = {}; {}return _rv; }}", cty(&self.func.ret), v, self.release_from(0));
                    }
                    Some(e) => {
                        let v = self.expr(e);
                        let _ = writeln!(out, "{};", v.code);
                        let _ = writeln!(out, "{}return;", self.release_from(0));
                    }
                    None => {
                        let _ = writeln!(out, "{}return;", self.release_from(0));
                    }
                }
            }
            Stmt::Block(b) => self.block(b, out),
        }
    }

    // ------------------------------------------------------------ places

    /// Emit temporaries for the index expressions of `p` (evaluated once, in path order).
    fn place_indices(&mut self, p: &Place, out: &mut String) -> Vec<Option<String>> {
        let mut names = Vec::new();
        for el in &p.path {
            match el {
                PlaceElem::Index(ix) => {
                    let id = self.fresh();
                    let v = self.expr(ix);
                    let _ = writeln!(out, "uint64_t _pi{} = {};", id, v.code);
                    names.push(Some(format!("_pi{}", id)));
                }
                PlaceElem::Field { .. } => names.push(None),
            }
        }
        names
    }

    /// Make every object on the path unique (writing replacements back into their parents).
    /// Afterwards `_c` is the container of the final element (or, with `whole`, the unique
    /// final object itself) and `_s` points at the final slot.
    fn place_walk(&mut self, p: &Place, idx: &[Option<String>], whole: bool, out: &mut String) {
        let r = p.root.0;
        let _ = writeln!(out, "l{r} = orin_make_unique(l{r});\nOrinObj *_c = l{r}; uint64_t *_s = 0; (void)_s;");
        let n = p.path.len();
        for (k, el) in p.path.iter().enumerate() {
            match el {
                PlaceElem::Field { index, .. } => {
                    let _ = writeln!(out, "_s = orin_struct_slot_ptr(_c, {});", index);
                }
                PlaceElem::Index(_) => {
                    let _ = writeln!(out, "_s = orin_array_slot_ptr(_c, {});", idx[k].as_ref().unwrap());
                }
            }
            if k + 1 < n || whole {
                out.push_str("_c = orin_make_unique(ORIN_REF(*_s)); *_s = ORIN_SLOT(_c);\n");
            }
        }
    }

    fn assign(&mut self, place: &Place, op: Option<BinOp>, value: &Expr, out: &mut String) {
        let ty = &place.ty;
        let r = place.root.0;
        // `s = s + x` on a string local is an append.
        let (op, value) = match (&op, &value.kind) {
            (None, ExprKind::Binary { op: BinOp::Add, lhs, rhs })
                if *ty == Type::String
                    && place.path.is_empty()
                    && matches!(lhs.kind, ExprKind::Local(l) if l == place.root) =>
            {
                (Some(BinOp::Add), &**rhs)
            }
            _ => (op, value),
        };
        // Fast path: scalar root local.
        if place.path.is_empty() && !is_ref(ty) && !has_effects(value) {
            let v = self.expr(value).code;
            match op {
                None => {
                    let _ = writeln!(out, "l{r} = {v};");
                }
                Some(o) => {
                    let _ = writeln!(out, "l{r} = {};", arith(o, ty, &format!("l{r}"), &v));
                }
            }
            return;
        }
        out.push_str("{\n");
        let idx = self.place_indices(place, out);
        let vt = cty(&value.ty);
        let vc = self.consume(value);
        let _ = writeln!(out, "{vt} _v = {vc};");
        self.place_walk(place, &idx, false, out);
        // lvalue accessors
        let (rd, wr): (String, Box<dyn Fn(&str) -> String>) = if place.path.is_empty() {
            (format!("l{r}"), Box::new(move |v: &str| format!("l{r} = {v};")))
        } else {
            let t = ty.clone();
            (from_slot(ty, "*_s"), Box::new(move |v: &str| format!("*_s = {};", to_slot(&t, v))))
        };
        match op {
            None => {
                if is_ref(ty) {
                    let _ = writeln!(out, "OrinObj *_o = {rd}; {} orin_release(_o);", wr("_v"));
                } else {
                    let _ = writeln!(out, "{}", wr("_v"));
                }
            }
            Some(BinOp::Add) if *ty == Type::String => {
                // Consumes the current value (held only by this slot); the result replaces it.
                let _ = writeln!(out, "{} orin_release(_v);", wr(&format!("orin_str_append({rd}, _v)")));
            }
            Some(o) => {
                let _ = writeln!(out, "{}", wr(&arith(o, ty, &rd, "_v")));
            }
        }
        out.push_str("}\n");
    }

    // ------------------------------------------------------------ expressions

    /// Compile `e` to an owned (+1) value.
    fn consume(&mut self, e: &Expr) -> String {
        let v = self.expr(e);
        self.consume_val(v, &e.ty)
    }

    fn consume_val(&self, v: Val, ty: &Type) -> String {
        if !is_ref(ty) || v.owned || v.imm {
            v.code
        } else {
            format!("orin_dup({})", v.code)
        }
    }

    /// Evaluate `args` left to right, then build the result with `f` from their C names.
    /// `consume[i]` = the callee takes ownership of arg i. Non-consumed owned temporaries are
    /// released afterwards; a result borrowed from them is retained first.
    fn seq(
        &mut self,
        args: &[(&Expr, bool)],
        rty: &Type,
        f: impl FnOnce(&[String]) -> (String, Kind),
    ) -> Val {
        let vals: Vec<Val> = args.iter().map(|(e, _)| self.expr(e)).collect();
        let n = args.len();
        let nonsimple = args.iter().filter(|(e, _)| !is_simple(e)).count();
        let eff: Vec<bool> = args.iter().map(|(e, _)| has_effects(e)).collect();
        let any_eff = eff.iter().any(|&b| b);
        // a borrowed reference arg followed by an effectful arg must be retained
        let mut later_eff = vec![false; n];
        let mut acc = false;
        for i in (0..n).rev() {
            later_eff[i] = acc;
            acc |= eff[i];
        }
        let pin = |i: usize, v: &Val| !args[i].1 && is_ref(&args[i].0.ty) && !v.owned && !v.imm && later_eff[i];
        let any_owned_borrow = (0..n).any(|i| !args[i].1 && is_ref(&args[i].0.ty) && vals[i].owned);
        let any_pin = (0..n).any(|i| pin(i, &vals[i]));
        let need_tmp = any_owned_borrow || any_pin || nonsimple >= 2 || (nonsimple == 1 && any_eff);

        if !need_tmp {
            let codes: Vec<String> = vals
                .into_iter()
                .enumerate()
                .map(|(i, v)| if args[i].1 { self.consume_val(v, &args[i].0.ty) } else { v.code })
                .collect();
            let (code, kind) = f(&codes);
            return match kind {
                Kind::Fresh if is_ref(rty) => Val::owned(code),
                _ => Val::borrowed(code),
            };
        }
        let id = self.fresh();
        let mut s = String::from("({ ");
        let mut names = Vec::new();
        let mut releases = String::new();
        for (i, v) in vals.into_iter().enumerate() {
            let ty = &args[i].0.ty;
            let name = format!("_t{}_{}", id, i);
            let init;
            if args[i].1 {
                init = self.consume_val(v, ty);
            } else if is_ref(ty) && (v.owned || pin(i, &v)) {
                init = if v.owned { v.code } else { format!("orin_dup({})", v.code) };
                let _ = write!(releases, "orin_release({}); ", name);
            } else {
                init = v.code;
            }
            let _ = write!(s, "{} {} = {}; ", cty(ty), name, init);
            names.push(name);
        }
        let (code, kind) = f(&names);
        match kind {
            Kind::Void => {
                let _ = write!(s, "{}; {}(void)0; }})", code, releases);
                Val::borrowed(s)
            }
            Kind::Fresh => {
                let _ = write!(s, "{} _r{} = {}; {}_r{}; }})", cty(rty), id, code, releases, id);
                if is_ref(rty) {
                    Val::owned(s)
                } else {
                    Val::borrowed(s)
                }
            }
            Kind::Borrowed => {
                if releases.is_empty() || !is_ref(rty) {
                    let _ = write!(s, "{} _r{} = {}; {}_r{}; }})", cty(rty), id, code, releases, id);
                    Val::borrowed(s)
                } else {
                    let _ = write!(s, "{} _r{} = orin_dup({}); {}_r{}; }})", cty(rty), id, code, releases, id);
                    Val::owned(s)
                }
            }
        }
    }

    fn expr(&mut self, e: &Expr) -> Val {
        match &e.kind {
            ExprKind::Int(n) => {
                let code = match e.ty {
                    Type::Usize => format!("((uint64_t){}ULL)", *n as u64),
                    _ if *n == i64::MIN => "INT64_MIN".to_string(),
                    _ => format!("((int64_t){}LL)", n),
                };
                Val::borrowed(code)
            }
            ExprKind::Bool(b) => Val::borrowed(if *b { "1" } else { "0" }.to_string()),
            ExprKind::Str(s) => {
                let id = self.g.intern(s);
                Val::imm(format!("orin_s{}", id))
            }
            ExprKind::Local(l) => Val::borrowed(format!("l{}", l.0)),
            ExprKind::Unary { op, expr } => {
                let v = self.expr(expr);
                let code = match op {
                    UnOp::Not => format!("(!{})", v.code),
                    UnOp::Neg if e.ty == Type::Usize => format!("orin_neg_u({})", v.code),
                    UnOp::Neg => format!("orin_neg_i({})", v.code),
                };
                Val::borrowed(code)
            }
            ExprKind::Binary { op, lhs, rhs } => match op {
                BinOp::And | BinOp::Or => {
                    let (a, b) = (self.expr(lhs).code, self.expr(rhs).code);
                    let o = if *op == BinOp::And { "&&" } else { "||" };
                    Val::borrowed(format!("({} {} {})", a, o, b))
                }
                _ => {
                    let (op, oty) = (*op, lhs.ty.clone());
                    self.seq(&[(lhs, false), (rhs, false)], &e.ty, move |a| {
                        (binary(op, &oty, &a[0], &a[1]), Kind::Fresh)
                    })
                }
            },
            ExprKind::Call { func, args } => {
                let name = self.names[func.0 as usize].clone();
                let a: Vec<(&Expr, bool)> = args.iter().map(|x| (x, false)).collect();
                self.seq(&a, &e.ty, move |c| {
                    let call = format!("{}({})", name, c.join(", "));
                    (call, if e.ty == Type::Void { Kind::Void } else { Kind::Fresh })
                })
            }
            ExprKind::Builtin { op, args } => {
                let a: Vec<(&Expr, bool)> = args.iter().map(|x| (x, false)).collect();
                let (op, ty) = (*op, e.ty.clone());
                self.seq(&a, &e.ty, move |c| builtin_call(op, c, &ty))
            }
            ExprKind::MutMethod { op, place, args } => self.mut_method(*op, place, args, &e.ty),
            ExprKind::Field { base, index, .. } => {
                let (idx, ty) = (*index, e.ty.clone());
                self.seq(&[(base, false)], &e.ty, move |c| {
                    (from_slot(&ty, &format!("orin_struct_get({}, {})", c[0], idx)), Kind::Borrowed)
                })
            }
            ExprKind::Index { base, index } => {
                let ty = e.ty.clone();
                self.seq(&[(base, false), (index, false)], &e.ty, move |c| {
                    (from_slot(&ty, &format!("orin_array_at({}, {})", c[0], c[1])), Kind::Borrowed)
                })
            }
            ExprKind::Record { record, spread, fields } => self.record(*record, spread.as_deref(), fields),
            ExprKind::Variant { tag, payload } => {
                if payload.is_empty() {
                    return Val::imm(format!("orin_nullary({})", tag));
                }
                let mask = mask_of(payload.iter().map(|p| &p.ty));
                let id = self.fresh();
                let mut s = format!("({{ OrinObj *_v{id} = orin_struct_new({tag}, {}, {mask}ULL); ", payload.len());
                for (i, p) in payload.iter().enumerate() {
                    let c = self.consume(p);
                    let _ = write!(s, "orin_struct_set(_v{id}, {i}, {}); ", to_slot(&p.ty, &c));
                }
                let _ = write!(s, "_v{id}; }})");
                Val::owned(s)
            }
            ExprKind::Array(xs) => {
                let elem_ref = match &e.ty {
                    Type::Array(t) => is_ref(t),
                    _ => unreachable!("array literal must have array type"),
                };
                let id = self.fresh();
                let mut s = format!("({{ OrinObj *_a{id} = orin_array_new({}, {}); ", xs.len(), elem_ref as i32);
                for x in xs {
                    let c = self.consume(x);
                    let _ = write!(s, "orin_array_push(_a{id}, {}); ", to_slot(&x.ty, &c));
                }
                let _ = write!(s, "_a{id}; }})");
                Val::owned(s)
            }
            ExprKind::Try(inner) => self.try_expr(inner, &e.ty),
            ExprKind::Cond { cond, then, els } => {
                let c = self.expr(cond).code;
                let (a, b) = (self.expr(then), self.expr(els));
                if !is_ref(&e.ty) {
                    Val::borrowed(format!("({} ? {} : {})", c, a.code, b.code))
                } else if !a.owned && !b.owned {
                    Val::borrowed(format!("({} ? {} : {})", c, a.code, b.code))
                } else {
                    let (a, b) = (self.consume_val(a, &e.ty), self.consume_val(b, &e.ty));
                    Val::owned(format!("({} ? {} : {})", c, a, b))
                }
            }
            ExprKind::Match { scrutinee, arms } => self.match_expr(scrutinee, arms, &e.ty),
        }
    }

    fn record(&mut self, record: RecordId, spread: Option<&Expr>, fields: &[(u32, Expr)]) -> Val {
        let def = &self.g.prog.records[record.0 as usize];
        let n = def.fields.len();
        let mask = mask_of(def.fields.iter().map(|(_, t)| t));
        let id = self.fresh();
        let mut s = String::from("({ ");
        let mut sp_owned = false;
        if let Some(sp) = spread {
            let v = self.expr(sp);
            sp_owned = v.owned;
            let _ = write!(s, "OrinObj *_sp{id} = {}; ", v.code);
        }
        let _ = write!(s, "OrinObj *_r{id} = orin_struct_new(0, {n}, {mask}ULL); ");
        if spread.is_some() {
            let explicit: Vec<u32> = fields.iter().map(|(i, _)| *i).collect();
            for i in 0..n as u32 {
                if !explicit.contains(&i) {
                    let _ = write!(s, "orin_struct_copy_slot(_r{id}, {i}, _sp{id}, {i}); ");
                }
            }
        }
        for (i, f) in fields {
            let c = self.consume(f);
            let _ = write!(s, "orin_struct_set(_r{id}, {i}, {}); ", to_slot(&f.ty, &c));
        }
        if sp_owned {
            let _ = write!(s, "orin_release(_sp{id}); ");
        }
        let _ = write!(s, "_r{id}; }})");
        Val::owned(s)
    }

    fn mut_method(&mut self, op: MutBuiltin, place: &Place, args: &[Expr], rty: &Type) -> Val {
        let mut s = String::from("({ ");
        let idx = self.place_indices(place, &mut s);
        match op {
            MutBuiltin::ArrPush => {
                let c = self.consume(&args[0]);
                let _ = write!(s, "{} _v = {}; ", cty(&args[0].ty), c);
                self.place_walk(place, &idx, true, &mut s);
                let _ = write!(s, "orin_array_push(_c, {}); (void)0; }})", to_slot(&args[0].ty, "_v"));
                Val::borrowed(s)
            }
            MutBuiltin::ArrPop => {
                self.place_walk(place, &idx, true, &mut s);
                let _ = rty;
                let _ = write!(s, "orin_array_pop(_c); }})");
                Val::owned(s)
            }
        }
    }

    fn try_expr(&mut self, inner: &Expr, ty: &Type) -> Val {
        let err_ty = match &inner.ty {
            Type::Result(_, e) => (**e).clone(),
            _ => unreachable!("? operand must be a Result"),
        };
        let v = self.expr(inner);
        let id = self.fresh();
        let t = format!("_tr{id}");
        let rel_t = if v.owned { format!("orin_release({t}); ") } else { String::new() };
        let err_slot = format!("orin_struct_get({t}, 0)");
        let err_dup = if is_ref(&err_ty) { format!("ORIN_SLOT(orin_dup(ORIN_REF({err_slot})))") } else { err_slot };
        let mask = is_ref(&err_ty) as u32;
        let mut s = format!("({{ OrinObj *{t} = {}; ", v.code);
        let _ = write!(
            s,
            "if (orin_tag({t}) == 1) {{ OrinObj *_er{id} = orin_variant1(1, {mask}, {err_dup}); {rel_t}{}return _er{id}; }} ",
            self.release_from(0)
        );
        match ty {
            Type::Void => {
                let _ = write!(s, "{rel_t}(void)0; }})");
                Val::borrowed(s)
            }
            _ if is_ref(ty) => {
                let _ = write!(
                    s,
                    "OrinObj *_ok{id} = orin_dup(ORIN_REF(orin_struct_get({t}, 0))); {rel_t}_ok{id}; }})"
                );
                Val::owned(s)
            }
            _ => {
                let _ = write!(s, "{} _ok{id} = {}; {rel_t}_ok{id}; }})", cty(ty), from_slot(ty, &format!("orin_struct_get({t}, 0)")));
                Val::borrowed(s)
            }
        }
    }

    fn match_expr(&mut self, scrut: &Expr, arms: &[MatchArm], ty: &Type) -> Val {
        let id = self.fresh();
        let sv = self.expr(scrut);
        let (sn, mv) = (format!("_ms{id}"), format!("_mv{id}"));
        let has_val = *ty != Type::Void;
        let mut s = String::from("({ ");
        if has_val {
            let _ = write!(s, "{} {mv}; ", cty(ty));
        }
        let _ = write!(s, "{} {sn} = {}; ", cty(&scrut.ty), sv.code);
        let own_scrut = sv.owned && is_ref(&scrut.ty);
        self.scopes.push(if own_scrut { vec![sn.clone()] } else { Vec::new() });
        let mut closed = false;
        for (i, arm) in arms.iter().enumerate() {
            let cond: Option<String> = match &arm.pattern {
                Pattern::Wildcard => None,
                Pattern::Variant { tag, .. } => Some(format!("orin_tag({sn}) == {tag}")),
                Pattern::Int(n) => Some(if scrut.ty == Type::Usize {
                    format!("{sn} == (uint64_t){}ULL", *n as u64)
                } else {
                    format!("{sn} == (int64_t){n}LL")
                }),
                Pattern::Bool(b) => Some(format!("{sn} == {}", *b as i32)),
                Pattern::Str(lit) => {
                    let k = self.g.intern(lit);
                    Some(format!("orin_str_eq({sn}, orin_s{k})"))
                }
            };
            match (&cond, i) {
                (Some(c), 0) => {
                    let _ = write!(s, "if ({c}) {{ ");
                }
                (Some(c), _) => {
                    let _ = write!(s, " else if ({c}) {{ ");
                }
                (None, 0) => s.push_str("{ "),
                (None, _) => s.push_str(" else { "),
            }
            // arm scope: bindings + statements + value
            self.scopes.push(Vec::new());
            if let Pattern::Variant { bindings, .. } = &arm.pattern {
                for (k, b) in bindings.iter().enumerate() {
                    if let Some(l) = b {
                        let lt = self.local_ty(*l).clone();
                        let slot = format!("orin_struct_get({sn}, {k})");
                        if is_ref(&lt) {
                            let _ = write!(s, "l{} = orin_dup(ORIN_REF({slot})); ", l.0);
                            self.scopes.last_mut().unwrap().push(format!("l{}", l.0));
                        } else {
                            let _ = write!(s, "l{} = {}; ", l.0, from_slot(&lt, &slot));
                        }
                    }
                }
            }
            let mut body = String::new();
            for st in &arm.body.stmts {
                self.stmt(st, &mut body);
            }
            s.push_str(&body);
            if let (Some(v), true) = (&arm.value, has_val) {
                let c = self.consume(v);
                let _ = write!(s, "{mv} = {c}; ");
            } else if let Some(v) = &arm.value {
                let v = self.expr(v);
                let _ = write!(s, "(void)({}); ", v.code);
            }
            s.push_str(&self.release_from(self.scopes.len() - 1));
            self.scopes.pop();
            s.push('}');
            if cond.is_none() {
                closed = true;
                break;
            }
        }
        if !closed {
            s.push_str(" else { orin_trap(\"non-exhaustive match\"); }");
        }
        self.scopes.pop();
        s.push(' ');
        if own_scrut {
            let _ = write!(s, "orin_release({sn}); ");
        }
        if has_val {
            let _ = write!(s, "{mv}; }})");
        } else {
            s.push_str("(void)0; })");
        }
        if has_val && is_ref(ty) {
            Val::owned(s)
        } else {
            Val::borrowed(s)
        }
    }
}

fn arith(op: BinOp, ty: &Type, a: &str, b: &str) -> String {
    let suffix = if *ty == Type::Usize { "u" } else { "i" };
    let name = match op {
        BinOp::Add => "add",
        BinOp::Sub => "sub",
        BinOp::Mul => "mul",
        BinOp::Div => "div",
        BinOp::Rem => "rem",
        _ => unreachable!("not an arithmetic operator"),
    };
    format!("orin_{name}_{suffix}({a}, {b})")
}

fn binary(op: BinOp, oty: &Type, a: &str, b: &str) -> String {
    match op {
        BinOp::Add if *oty == Type::String => format!("orin_str_concat({a}, {b})"),
        BinOp::Add | BinOp::Sub | BinOp::Mul | BinOp::Div | BinOp::Rem => arith(op, oty, a, b),
        BinOp::Eq if *oty == Type::String => format!("orin_str_eq({a}, {b})"),
        BinOp::Ne if *oty == Type::String => format!("(!orin_str_eq({a}, {b}))"),
        BinOp::Eq => format!("({a} == {b})"),
        BinOp::Ne => format!("({a} != {b})"),
        BinOp::Lt => format!("({a} < {b})"),
        BinOp::Le => format!("({a} <= {b})"),
        BinOp::Gt => format!("({a} > {b})"),
        BinOp::Ge => format!("({a} >= {b})"),
        BinOp::And | BinOp::Or => unreachable!("short-circuit operators are handled by the caller"),
    }
}

fn builtin_call(op: Builtin, a: &[String], ty: &Type) -> (String, Kind) {
    use Builtin::*;
    let f = |s: String| (s, Kind::Fresh);
    let v = |s: String| (s, Kind::Void);
    let b = |s: String| (s, Kind::Borrowed);
    match op {
        ConsoleLog => v(format!("orin_console_log({})", a[0])),
        ConsoleError => v(format!("orin_console_error({})", a[0])),
        StringFromCharCode => f(format!("orin_string_from_char_code({})", a[0])),
        ParseInt => f(format!("orin_parse_int({})", a[0])),
        FsReadFile => f(format!("orin_fs_read_file({})", a[0])),
        FsWriteFile => f(format!("orin_fs_write_file({}, {})", a[0], a[1])),
        FsExists => f(format!("orin_fs_exists({})", a[0])),
        ProcessArgs => f("orin_process_args()".to_string()),
        ProcessExit => v(format!("orin_process_exit({})", a[0])),
        StrLength => f(format!("orin_str_len({})", a[0])),
        StrCharCodeAt => f(format!("orin_str_char_code_at({}, {})", a[0], a[1])),
        StrCharAt => f(format!("orin_str_char_at({}, {})", a[0], a[1])),
        StrSubstring => f(format!("orin_str_substring({}, {}, {})", a[0], a[1], a[2])),
        StrIndexOf => f(format!("orin_str_index_of({}, {})", a[0], a[1])),
        StrIncludes => f(format!("orin_str_includes({}, {})", a[0], a[1])),
        StrStartsWith => f(format!("orin_str_starts_with({}, {})", a[0], a[1])),
        StrEndsWith => f(format!("orin_str_ends_with({}, {})", a[0], a[1])),
        StrSplit => f(format!("orin_str_split({}, {})", a[0], a[1])),
        StrTrim => f(format!("orin_str_trim({})", a[0])),
        ArrLength => f(format!("orin_array_len({})", a[0])),
        ArrGet => f(format!("orin_array_get({}, {})", a[0], a[1])),
        ArrSlice => f(format!("orin_array_slice({}, {}, {})", a[0], a[1], a[2])),
        ArrConcat => f(format!("orin_array_concat({}, {})", a[0], a[1])),
        ArrJoin => f(format!("orin_array_join({}, {})", a[0], a[1])),
        IntToString => f(format!("orin_int_to_string({})", a[0])),
        IntToUsize => f(format!("orin_int_to_usize({})", a[0])),
        UsizeToString => f(format!("orin_usize_to_string({})", a[0])),
        UsizeToInt => f(format!("orin_usize_to_int({})", a[0])),
        BoolToString => f(format!("orin_bool_to_string({})", a[0])),
        OptIsSome => f(format!("(orin_tag({}) == 0)", a[0])),
        OptIsNone => f(format!("(orin_tag({}) == 1)", a[0])),
        ResIsOk => f(format!("(orin_tag({}) == 0)", a[0])),
        ResIsErr => f(format!("(orin_tag({}) == 1)", a[0])),
        OptUnwrap => b(from_slot(ty, &format!("orin_opt_unwrap({})", a[0]))),
        OptUnwrapOr => b(format!(
            "(orin_tag({0}) == 0 ? {1} : {2})",
            a[0],
            from_slot(ty, &format!("orin_struct_get({}, 0)", a[0])),
            a[1]
        )),
        ResUnwrap if *ty == Type::Void => v(format!("(void)orin_res_unwrap({})", a[0])),
        ResUnwrap => b(from_slot(ty, &format!("orin_res_unwrap({})", a[0]))),
        ResUnwrapErr => b(from_slot(ty, &format!("orin_res_unwrap_err({})", a[0]))),
    }
}
