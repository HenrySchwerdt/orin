#!/usr/bin/env python3
"""Embed the Orin prelude sources into the compiler (spec 19, R1; docs/architecture.md "Preludes").

The self-hosted compiler is a single native binary and cannot locate files next to itself, so each
prelude directory (library/core/, ...) is compiled into the compiler as a generated Orin file that returns
its sources as `SourceFile[]` (virtual paths `<unit prefix>/<file>`). The loader serves them through
its overlay mechanism (compiler/loader/prelude.or).

To add a prelude: append a row to PRELUDES here, add one `PreludeRoot` to `preludeRoots()` in
compiler/loader/prelude.or, and run this script. Unit prefixes start with `$`.

Usage: python3 tools/embed_prelude.py [--check]
  (no flag)  rewrite the generated files;
  --check    exit 1 if a generated file is stale (used by tools/bootstrap.sh).
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# (source dir, unit prefix, generated file, exported function)
PRELUDES = [
    ("library/core", "$std", "compiler/loader/embedded_std.or", "embeddedStdFiles"),
    ("library/collections", "$array", "compiler/loader/embedded_array.or", "embeddedArrayFiles"),
    ("library/std", "$stdlib", "compiler/loader/embedded_stdlib.or", "embeddedStdlibFiles"),
]


def esc(data):
    out = []
    for b in data:
        c = chr(b)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
        elif c == "\t":
            out.append("\\t")
        elif c == "\r":
            out.append("\\r")
        elif 32 <= b < 127:
            out.append(c)
        else:
            out.append("\\x%02x" % b)
    return "".join(out)


def render(src_dir, prefix, outfile, func):
    d = os.path.join(ROOT, src_dir)
    # Sub-directories are part of the root (std:json/number is library/std/json/number.or).
    names = sorted(
        os.path.relpath(os.path.join(dp, f), d).replace(os.sep, "/")
        for dp, _, fs in os.walk(d)
        for f in fs
        if f.endswith(".or")
    )
    lines = [
        "// GENERATED by tools/embed_prelude.py from %s/ -- do not edit; run the script after changing the sources." % src_dir,
        "",
        'import { SourceFile } from "../diag";',
        "",
        "export function %s(): SourceFile[] {" % func,
        "  let out: SourceFile[] = [];",
    ]
    for n in names:
        with open(os.path.join(d, n), "rb") as f:
            text = f.read()
        lines.append('  out.push(SourceFile { path: "%s/%s", text: "%s" });' % (prefix, n, esc(text)))
    lines += ["  return out;", "}", ""]
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for src_dir, prefix, outfile, func in PRELUDES:
        text = render(src_dir, prefix, outfile, func)
        path = os.path.join(ROOT, outfile)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text:
            if check:
                stale.append(outfile)
            else:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(text)
                print("wrote", outfile)
    if stale:
        print("stale generated prelude file(s): %s -- run python3 tools/embed_prelude.py" % ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
