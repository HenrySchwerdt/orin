#!/bin/sh
# Renders the Homebrew formula (Formula/orin.rb of the orin-lang/homebrew-orin tap) for one published release.
#   tools/homebrew_formula.sh <version> <sha256 of orin-<version>-macos-arm64.tar.gz>    formula on stdout
#   tools/homebrew_formula.sh <version> --sums <SHA256SUMS>                               same, sha256 read from SHA256SUMS
# Only the macOS ARM64 package is in the formula (ADR-0047 section 6): Intel and Linux follow once their
# Homebrew smoke tests exist. The release workflow uses this to open a formula update PR on the tap.
set -eu
[ $# -ge 2 ] || { echo "usage: $0 <version> <sha256> | <version> --sums <SHA256SUMS>" >&2; exit 2; }
ver=$1
printf '%s' "$ver" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+([-+][0-9A-Za-z.+-]+)?$' || { echo "bad version '$ver'" >&2; exit 2; }
pkg="orin-$ver-macos-arm64.tar.gz"
if [ "$2" = "--sums" ]; then
  [ $# -eq 3 ] || { echo "usage: $0 <version> --sums <SHA256SUMS>" >&2; exit 2; }
  sha=$(awk -v f="$pkg" '$2 == f || $2 == "*" f { print $1 }' "$3")
else
  sha=$2
fi
printf '%s' "$sha" | grep -Eq '^[0-9a-f]{64}$' || { echo "no valid sha256 for $pkg (got '$sha')" >&2; exit 1; }
cat <<RUBY
# Generated by tools/homebrew_formula.sh in orin-lang/orin-lang; the release workflow opens a PR with each new version.
class Orin < Formula
  desc "Compiler for Orin, a statically typed language with verified contracts"
  homepage "https://github.com/orin-lang/orin-lang"
  url "https://github.com/orin-lang/orin-lang/releases/download/v$ver/$pkg"
  version "$ver"
  sha256 "$sha"
  license "MIT"

  depends_on arch: :arm64
  depends_on :macos

  def install
    # The release package is relocatable: bin/orin finds libexec/ and lib/orin/ relative to itself, so the whole
    # package goes to libexec and bin/orin is a wrapper that execs the real launcher by its path.
    libexec.install Dir["*"]
    bin.write_exec_script libexec/"bin/orin"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/orin --version").strip
    system bin/"orin", "doctor"
    (testpath/"hello.or").write <<~ORIN
      function main(): void {
        console.log("Hello from Homebrew!");
      }
    ORIN
    assert_equal "Hello from Homebrew!", shell_output("#{bin}/orin run hello.or").strip
    system bin/"orin", "build", "hello.or", "-o", "hello"
    assert_equal "Hello from Homebrew!", shell_output("./hello").strip
  end
end
RUBY
