#!/bin/sh
# Generate src/theme_css.or from theme/report.css (the readable source of the design system).
# OX allows only a static string literal inside <style>, so the stylesheet is embedded as one literal; the file is
# generated, never edited by hand. Usage: tooling/reports/gen_theme.sh [--check]
#   --check  exit 1 when src/theme_css.or is not what the generator would write (run by tooling/reports/test.sh)
set -eu
cd "$(dirname "$0")"
css=theme/report.css
out=src/theme_css.or
version=$(sed -n 's|^/\* orin-reports design system, version \([0-9][0-9]*\)\..*|\1|p' "$css")
[ -n "$version" ] || { echo "gen_theme: version comment missing in $css" >&2; exit 1; }
if grep -q '["\\]' "$css"; then
  echo "gen_theme: $css must not contain a double quote or a backslash (use single quotes)" >&2
  exit 1
fi
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
{
  echo "// GENERATED by tooling/reports/gen_theme.sh from theme/report.css. Do not edit; edit the CSS and regenerate."
  echo "import ox from \"std:html\";"
  echo "import { Html } from \"std:html\";"
  echo
  echo "export const THEME_VERSION: string = \"$version\";"
  echo
  echo "// The whole stylesheet as one static literal: <style> accepts nothing computed (E0493), so nothing is spliced in."
  echo "export function ThemeStyle(): Html {"
  printf '  return <style>{"'
  awk 'BEGIN { first = 1 } { if (!first) printf "\\n"; first = 0; printf "%s", $0 } END { printf "\\n" }' "$css"
  echo '"}</style>;'
  echo "}"
} > "$tmp"
if [ "${1:-}" = "--check" ]; then
  cmp -s "$tmp" "$out" || { echo "gen_theme: $out is stale; run tooling/reports/gen_theme.sh" >&2; exit 1; }
else
  cp "$tmp" "$out"
fi
