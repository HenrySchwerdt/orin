#!/usr/bin/env python3
"""Differential test: Lean ownership checker (`Orin.check`, the function `check_sound` is about,
run through formal/Orin/Exec.lean) against the real verifier `compiler/verify` (run through the
driver compiler/tests/verify_text.or) on generated programs of the structured MIR fragment.

Every program is generated by tools/gen_mir_fragment.py (deterministic seed), checked by both, and
the ACCEPT/REJECT verdicts are compared. For every base program two random top-level prefixes are
checked as well (this pins down *where* the first fault is, not only whether there is one).

A divergence must be explained by an entry of ALLOW below (a known, documented difference of the
model from the verifier). An entry only excuses a divergence if re-running the Lean checker on a
*rewritten* program, in which the modelling restriction is expressed in the Lean fragment, gives
the verifier's verdict: the divergence is then exactly that restriction and nothing else. Any
other divergence fails the run. Divergences where the verifier ACCEPTS and Lean REJECTS are the
dangerous direction and are always listed, allow-listed or not.

What this establishes: on these programs the two implementations of the rules give the same
verdicts. It is evidence (assurance level TESTED_ONLY), not a proof that compiler/verify
implements the Lean checker.

Usage: python3 tools/diff_verifier_lean.py [--count 2000] [--seed N] [--orinc build/bootstrap/orin2]
"""
import argparse
import os
import random
import subprocess
import sys
import tempfile
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import gen_mir_fragment as gen  # noqa: E402


# ---------------------------------------------------------------- running both checkers

def build_driver(orinc, out_dir):
    c = os.path.join(out_dir, "verify_text.c")
    exe = os.path.join(out_dir, "verify_text")
    subprocess.run([orinc, "compile", "compiler/tests/verify_text.or", "-o", c], cwd=ROOT, check=True)
    subprocess.run(["cc", "-O1", "-w", "-I", "runtime/core", c, "runtime/core/orin_runtime.c",
                    "runtime/platform/orin_platform.c", "-lm", "-o", exe], cwd=ROOT, check=True)
    return exe


def run_lean(exe, progs, tmp):
    path = os.path.join(tmp, "lean.txt")
    with open(path, "w") as f:
        for p in progs:
            f.write(gen.to_lean(p))
    r = subprocess.run([exe, path], capture_output=True, text=True, timeout=600)
    if r.returncode != 0:
        sys.exit("orin_check failed: " + r.stderr[:500])
    out = {}
    for line in r.stdout.splitlines():
        name, verdict, *rest = line.split(" ", 2)
        if verdict not in ("ACCEPT", "REJECT"):
            sys.exit("orin_check: " + line)
        out[name] = (verdict, rest[0] if rest else "")
    return out


def run_verifier(exe, progs, tmp):
    path = os.path.join(tmp, "mir.txt")
    with open(path, "w") as f:
        for p in progs:
            # with source positions on every line (docs/mir.md v2.0): the driver must read and ignore them
            f.write("=== %s\n%s" % (p.name, gen.to_mir(p, spans=True)))
    r = subprocess.run([exe, path], capture_output=True, text=True, timeout=600)
    if r.returncode != 0:
        sys.exit("verify_text failed: " + r.stderr[:500])
    out = {}
    for line in r.stdout.splitlines():
        parts = line.split("\t")
        out[parts[0]] = (parts[1], parts[3] if len(parts) > 3 else "")
    return out


# ---------------------------------------------------------------- allow-list

def _rewrite_self_operand(code):
    """IStructNew d [.. d ..]: the verifier consumes d (it must be counted) and then redefines it.
    In the Lean fragment that is `release d` once per occurrence, then the struct without d."""
    out, changed = [], False
    for st in code:
        if st[0] == "struct" and st[1] in st[2]:
            k = st[2].count(st[1])
            out += [("release", st[1])] * k
            out.append(("struct", st[1], [y for y in st[2] if y != st[1]]))
            changed = True
        elif st[0] == "if":
            t, c1 = _rewrite_self_operand(st[2])
            e, c2 = _rewrite_self_operand(st[3])
            out.append(("if", st[1], t, e))
            changed = changed or c1 or c2
        else:
            out.append(st)
    return out, changed


def rewrite_self_operand(p):
    code, changed = _rewrite_self_operand(p.code)
    if not changed:
        return None
    q = gen.Prog(p.name + "_rw", p.cls, p.np, code)
    return q


# (id, reference, reason, rewrite: Prog -> Prog | None)
ALLOW = [
    ("F6-structNew-self-operand", "docs/formal.md Finding 6",
     "IStructNew whose operand list contains its own destination: rules.or consumes the operands "
     "and then defines d, so it is accepted when d is counted; the Lean model expands IStructNew to "
     "`alloc d` + `setField d i y` and therefore rejects it. Excused only if the Lean verdict on the "
     "program with `release d` + the struct without d equals the verifier's verdict.",
     rewrite_self_operand),
]
# Finding 5 (setField/putField with v == x) needs no entry: wf.or and the model both reject it.


# ---------------------------------------------------------------- main

def prefixes(p, rng, k=2):
    n = len(p.code)
    out = []
    for j in range(k):
        if n < 2:
            break
        cut = rng.randint(1, n - 1)
        out.append(gen.Prog("%s_pre%d" % (p.name, j), p.cls, p.np, p.code[:cut]))
    return out


def coverage(progs):
    kinds = {}
    for p in progs:
        for st in gen.walk(p.code):
            kinds[st[0]] = kinds.get(st[0], 0) + 1
    return kinds


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--count", type=int, default=4000, help="base programs (prefixes are added)")
    ap.add_argument("--seed", type=int, default=20261013)
    ap.add_argument("--orinc", default=os.path.join(ROOT, "build", "bootstrap", "orin2"))
    ap.add_argument("--lean-exe", default=os.path.join(ROOT, "formal", ".lake", "build", "bin", "orin_check"))
    ap.add_argument("--verify-text", default=None, help="prebuilt driver (default: build it)")
    ap.add_argument("-v", action="store_true")
    a = ap.parse_args()
    t0 = time.time()
    if not os.path.exists(a.lean_exe):
        sys.exit("missing %s (run `lake build orin_check` in formal/)" % a.lean_exe)
    with tempfile.TemporaryDirectory() as tmp:
        drv = a.verify_text or build_driver(a.orinc, tmp)
        base = gen.generate(a.count, a.seed)
        rng = random.Random(a.seed ^ 0x5eed)
        progs = list(base)
        for p in base:
            progs += prefixes(p, rng)
        lean = run_lean(a.lean_exe, progs, tmp)
        ver = run_verifier(drv, progs, tmp)
        if set(lean) != set(ver) or len(lean) != len(progs):
            sys.exit("result sets differ (%d lean, %d verifier, %d programs)" % (len(lean), len(ver), len(progs)))

        div = [p for p in progs if lean[p.name][0] != ver[p.name][0]]
        # re-run Lean on the rewritten programs of the allow-list candidates
        rewrites = {}
        for p in div:
            for entry in ALLOW:
                q = entry[3](p)
                if q is not None:
                    rewrites[(entry[0], p.name)] = q
        rw_lean = run_lean(a.lean_exe, list(rewrites.values()), tmp) if rewrites else {}

        classes = {}  # id -> list of (prog, direction)
        unexplained = []
        for p in div:
            direction = ("verifier ACCEPTS, Lean REJECTS" if ver[p.name][0] == "ACCEPT"
                         else "verifier REJECTS, Lean ACCEPTS")
            for entry in ALLOW:
                q = rewrites.get((entry[0], p.name))
                if q is not None and rw_lean[q.name][0] == ver[p.name][0]:
                    classes.setdefault(entry[0], []).append((p, direction))
                    break
            else:
                unexplained.append((p, direction))

    acc_both = sum(1 for p in progs if lean[p.name][0] == ver[p.name][0] == "ACCEPT")
    rej_both = sum(1 for p in progs if lean[p.name][0] == ver[p.name][0] == "REJECT")
    cov = coverage(progs)
    print("programs: %d (%d base + prefixes), seed %d" % (len(progs), len(base), a.seed))
    print("instruction mix: " + ", ".join("%s %d" % kv for kv in sorted(cov.items())))
    print("both ACCEPT: %d   both REJECT: %d   diverging: %d" % (acc_both, rej_both, len(div)))
    reasons = {}
    for p in progs:
        if lean[p.name][0] == "REJECT":
            r = lean[p.name][1]
            while r.startswith(("then-branch: ", "else-branch: ")):
                r = r.split(": ", 1)[1]
            key = r.split("instruction rejected: ")[1].split(" ")[0] if "instruction rejected" in r else ("if condition" if r.startswith("if condition") else r.split(" (")[0])
            reasons[key] = reasons.get(key, 0) + 1
    print("Lean rejected at: " + ", ".join("%s %d" % kv for kv in sorted(reasons.items())))
    dangerous = False
    for entry in ALLOW:
        items = classes.get(entry[0], [])
        print("allow-listed %s (%s): %d divergence(s)" % (entry[0], entry[1], len(items)))
        if not items:
            print("   WARNING: entry never matched (stale?)")
        for p, direction in items[:1]:
            print("   example %s: %s; Lean: %s; verifier: %s" % (p.name, direction, lean[p.name][1], ver[p.name][1][:100]))
        if any(d.startswith("verifier ACCEPTS") for _, d in items):
            dangerous = True
            print("   direction verifier ACCEPTS / Lean REJECTS in %d case(s): the verifier is more permissive than the model"
                  % sum(1 for _, d in items if d.startswith("verifier ACCEPTS")))
    for p, direction in unexplained:
        print("UNEXPLAINED DIVERGENCE %s (%s)\n   Lean: %s\n   verifier: %s\n%s" % (
            p.name, direction, lean[p.name][1], ver[p.name][1], gen.to_mir(p)))
    print("time %.1fs" % (time.time() - t0))
    if unexplained:
        print("FAIL: %d unexplained divergence(s)" % len(unexplained))
        return 1
    print("OK: all verdicts agree up to the %d allow-listed class(es)%s" % (
        len(ALLOW), " (verifier-more-permissive cases listed above)" if dangerous else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
