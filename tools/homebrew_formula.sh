#!/bin/sh
# Renders the Homebrew formula (Formula/orin.rb of the orin-lang/homebrew-orin tap) for one published release.
#   tools/homebrew_formula.sh <version> --sums <SHA256SUMS>                               every platform in SHA256SUMS
#   tools/homebrew_formula.sh <version> <sha256 of orin-<version>-macos-arm64.tar.gz>    macOS arm64 only
# With --sums the formula covers each of macos-arm64, macos-x86_64, linux-x86_64 and linux-aarch64 whose package is
# listed in SHA256SUMS (macos-arm64 is required); a platform without a package is left out of the formula. The release
# workflow uses this to open a formula update PR on the tap and attaches the rendered orin.rb to the release.
set -eu
[ $# -ge 2 ] || { echo "usage: $0 <version> <sha256> | <version> --sums <SHA256SUMS>" >&2; exit 2; }
ver=$1
printf '%s' "$ver" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+([-+][0-9A-Za-z.+-]+)?$' || { echo "bad version '$ver'" >&2; exit 2; }
base="https://github.com/orin-lang/orin-lang/releases/download/v$ver"

# sha256 of orin-<ver>-<plat>.tar.gz, empty when the platform is not in the sums file.
sha_of() {
  if [ "$sums" = "" ]; then
    [ "$1" = macos-arm64 ] && printf '%s' "$single"
    return 0
  fi
  awk -v f="orin-$ver-$1.tar.gz" '$2 == f || $2 == "*" f { print $1 }' "$sums"
}

sums=""
single=""
if [ "$2" = "--sums" ]; then
  [ $# -eq 3 ] || { echo "usage: $0 <version> --sums <SHA256SUMS>" >&2; exit 2; }
  sums=$3
  [ -f "$sums" ] || { echo "no such file: $sums" >&2; exit 1; }
else
  single=$2
fi

mac_arm=$(sha_of macos-arm64)
mac_x86=$(sha_of macos-x86_64)
lin_x86=$(sha_of linux-x86_64)
lin_arm=$(sha_of linux-aarch64)
for s in "$mac_arm" "$mac_x86" "$lin_x86" "$lin_arm"; do
  [ -z "$s" ] || printf '%s' "$s" | grep -Eq '^[0-9a-f]{64}$' || { echo "bad sha256 '$s'" >&2; exit 1; }
done
[ -n "$mac_arm" ] || { echo "no valid sha256 for orin-$ver-macos-arm64.tar.gz" >&2; exit 1; }

# One url/sha256 pair, indented for its block.
pkg() { # <indent> <plat> <sha>
  printf '%surl "%s/orin-%s-%s.tar.gz"\n%ssha256 "%s"\n' "$1" "$base" "$ver" "$2" "$1" "$3"
}

cat <<RUBY
# Generated by tools/homebrew_formula.sh in orin-lang/orin-lang; the release workflow opens a PR with each new version.
class Orin < Formula
  desc "Compiler for Orin, a statically typed language with verified contracts"
  homepage "https://github.com/orin-lang/orin-lang"
  version "$ver"
  license "MIT"

  on_macos do
    on_arm do
$(pkg "      " macos-arm64 "$mac_arm")
    end
RUBY
if [ -n "$mac_x86" ]; then
  printf '    on_intel do\n%s\n    end\n' "$(pkg "      " macos-x86_64 "$mac_x86")"
else
  printf '    depends_on arch: :arm64\n'
fi
printf '  end\n'
if [ -n "$lin_x86" ] || [ -n "$lin_arm" ]; then
  printf '\n  on_linux do\n'
  if [ -n "$lin_x86" ]; then printf '    on_intel do\n%s\n    end\n' "$(pkg "      " linux-x86_64 "$lin_x86")"; fi
  if [ -n "$lin_arm" ]; then printf '    on_arm do\n%s\n    end\n' "$(pkg "      " linux-aarch64 "$lin_arm")"; fi
  printf '  end\n'
else
  printf '\n  depends_on :macos\n'
fi
cat <<RUBY

  def install
    # The release package is relocatable: bin/orin finds libexec/ and lib/orin/ relative to itself, so the whole
    # package goes to libexec and bin/orin is a wrapper that execs the real launcher by its path.
    libexec.install Dir["*"]
    bin.write_exec_script libexec/"bin/orin"
  end

  def caveats
    <<~EOS
      orin compiles through C: it needs a C compiler on PATH (Xcode Command Line Tools on macOS, gcc or clang on
      Linux). Run \`orin doctor\` to check the toolchain. Getting started:
        https://github.com/orin-lang/orin-lang/blob/main/docs/tutorial/README.md
    EOS
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/orin --version").strip
    system bin/"orin", "doctor"
    (testpath/"hello.or").write <<~ORIN
      function main(): void {
        console.log("Hello from Homebrew!");
      }
    ORIN
    assert_equal "Hello from Homebrew!", shell_output("#{bin}/orin run hello.or").strip
    system bin/"orin", "build", "hello.or", "-o", "hello"
    assert_equal "Hello from Homebrew!", shell_output("./hello").strip
  end
end
RUBY
