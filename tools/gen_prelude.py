#!/usr/bin/env python3
"""Generates compiler/prelude/source.or from compiler/prelude/array.or (ADR-0011).

The array prelude is Orin source that the compiler injects into every program; since the compiler
binary cannot read files at an unknown location, the text is embedded as a string constant in an
Orin-B module (compiler/prelude/source.or), which this script writes.

Usage: python3 tools/gen_prelude.py          regenerate
       python3 tools/gen_prelude.py --check  exit 1 if source.or is stale
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "compiler", "prelude", "array.or")
OUT = os.path.join(ROOT, "compiler", "prelude", "source.or")


def quote(line):
    out = ['"']
    for ch in line:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def generate():
    text = open(SRC, encoding="utf-8").read()
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    body = ",\n".join("    " + quote(l) for l in lines)
    return (
        "// GENERATED by tools/gen_prelude.py from compiler/prelude/array.or. Do not edit.\n"
        "// The array prelude (ADR-0011) as text; check/checker.or parses it as a hidden unit.\n"
        "\n"
        "export function preludeArraySource(): string {\n"
        "  const lines: string[] = [\n" + body + "\n  ];\n"
        "  return lines.join(\"\\n\") + \"\\n\";\n"
        "}\n"
    )


def main():
    want = generate()
    if "--check" in sys.argv:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != want:
            sys.exit("compiler/prelude/source.or is stale: run python3 tools/gen_prelude.py")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(want)


if __name__ == "__main__":
    main()
